#!/usr/bin/env python3
"""
scripts/generate_env_example.py

Writes `.env.example` from `app.config.Settings.model_fields`, so the example
file can never drift from the real settings: every setting appears, with its
description and its default. `tests/test_env_example.py` fails if the committed
file differs from what this script would write.

    python scripts/generate_env_example.py          # rewrite .env.example
    python scripts/generate_env_example.py --check  # exit 1 if it is out of date

No value here is a secret: required settings are left empty, optional ones are
shown commented out with their default.
"""
from __future__ import annotations

import argparse
import json
import sys
import textwrap
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from pydantic_core import PydanticUndefined  # noqa: E402

from app.config import Settings  # noqa: E402

TARGET = REPO / ".env.example"
HEADER = """\
# Generated by scripts/generate_env_example.py from app/config.py -- do not edit by hand.
# Copy to .env and fill in the values marked REQUIRED.
# Every setting is read from the environment; the names are the field names in
# app/config.py, upper-cased. Lines starting with '# NAME=' show the default and
# are optional. Lists and objects are written as JSON.
"""


def _render_default(value) -> str:
    if value is None:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, Path):
        return value.as_posix()
    if isinstance(value, (list, dict)):
        return json.dumps(value)
    return str(value)


def render() -> str:
    lines = [HEADER]
    for name, info in Settings.model_fields.items():
        env = name.upper()
        if info.description:
            for chunk in textwrap.wrap(" ".join(info.description.split()), width=96):
                lines.append(f"# {chunk}")
        if info.is_required():
            lines.append(f"{env}=   # REQUIRED")
        else:
            default = info.default_factory() if info.default_factory is not None else info.default
            if default is PydanticUndefined:
                default = None
            lines.append(f"# {env}={_render_default(default)}")
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[1])
    ap.add_argument("--check", action="store_true", help="only report whether .env.example is up to date")
    args = ap.parse_args(argv)
    text = render()
    current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else None
    if args.check:
        if current != text:
            print(".env.example is out of date; run: python scripts/generate_env_example.py")
            return 1
        print(".env.example is up to date.")
        return 0
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(REPO)} ({len(Settings.model_fields)} settings)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
